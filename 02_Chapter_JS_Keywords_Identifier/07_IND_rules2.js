//Naming conventions for identifiers in JavaScript:

//1. Camel Case: The first letter of the identifier is lowercase, and the first letter of each subsequent word is capitalized. 
// For example: firstName, lastName, myVariable.
   let firstName="Kavya"; //This is a valid identifier, can start with letter.
   let lastName="Jogdand"; //This is a valid identifier, can start with letter.
   let myVariable="Hello"; //This is a valid identifier, can start with letter.
   let totalAmount=100; //This is a valid identifier, can start with letter.
   let totalAge=1; //This is a valid identifier, can start with letter.

//2. Pascal Case: The first letter of each word in the identifier is capitalized. 
// For example: FirstName, LastName, MyVariable.
   let FirstName="Kavya"; //This is a valid identifier, can start with letter.
   let LastName="Jogdand"; //This is a valid identifier, can start with letter.
   let MyVariable="Hello"; //This is a valid identifier, can start with letter.
   let TotalAmount=100; //This is a valid identifier, can start with letter.
   let TotalAge=1; //This is a valid identifier, can start with letter. 

//3. Snake Case: Words in the identifier are separated by underscores. 
// For example: first_name, last_name, my_variable.
   let first_name="Kavya"; //This is a valid identifier, can start with letter.
   let last_name="Jogdand"; //This is a valid identifier, can start with letter.
   let my_variable="Hello"; //This is a valid identifier, can start with letter.
   let total_amount=100; //This is a valid identifier, can start with letter.
   let total_age=1; //This is a valid identifier, can start with letter.

//4. Kebab Case: Words in the identifier are separated by hyphens. 
// For example: first-name, last-name, my-variable.
