let a = 10; //Literal - value assigned to variable
let b = 20; //Literal - value assigned to variable 
let c = a + b; //Literal - value assigned to variable

// Type of Literals in JavaScript
// 1. String Literals
let str = "Hello, World!"; //String Literal

// 2. Numeric Literals
let num = 42; //Numeric Literal

// 3. Boolean Literals
let isTrue = true; //Boolean Literal
let isFalse = false; //Boolean Literal

// 4. Array Literals
let arr = [1, 2, 3, 4, 5]; //Array Literal

// 5. Object Literals
let obj = { name: "John", age: 30 }; //Object Literal

// 6. Null Literal
let nullValue = null; //Null Literal

// 7. Undefined Literal
let undefinedValue; //Undefined Literal (implicitly undefined)  