//Numeric Literals types
// 1. Integer Literals
let intNum = 42; //Integer Literal

// 2. Floating Point Literals
let floatNum = 3.14; //Floating Point Literal

// 3. Exponential Notation Literals
let expNum = 1.23e4; //Exponential Notation Literal (1.23 * 10^4)

// 4. Hexadecimal Literals
let hexNum = 0xFF; //Hexadecimal Literal (255 in decimal)

// 5. Octal Literals
let octNum = 0o77; //Octal Literal (63 in decimal)

// 6. Binary Literals
let binNum = 0b1010; //Binary Literal (10 in decimal)       


