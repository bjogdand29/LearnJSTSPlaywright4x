// All Number Types in JavaScript

// 1. Integer
let intNum = 42; //Integer Literal

// 2. Floating Point
let floatNum = 3.14; //Floating Point Literal
let floatNum2 = 0.5; //Floating Point Literal
let floatNum3 = 2.5; //Floating Point Literal
let floatNum4 = 5.0; //Floating Point Literal

// 3. Exponential Notation
let expNum = 1.23e4; //Exponential Notation Literal (1.23 * 10^4)

// 4. Hexadecimal
let hexNum = 0xFF; //Hexadecimal Literal (255 in decimal)

// 5. Octal
let octNum = 0o77; //Octal Literal (63 in decimal)

// 6. Binary
let binNum = 0b1010; //Binary Literal (10 in decimal)

// 7. BigInt
let bigIntNum = 1234567890123456789012345678901234567890n; //BigInt Literal

//Typeof Number Literals in JavaScript
console.log(typeof intNum); //number
console.log(typeof floatNum); //number
console.log(typeof expNum); //number
console.log(typeof hexNum); //number
console.log(typeof octNum); //number
console.log(typeof binNum); //number
console.log(typeof bigIntNum); //bigint 