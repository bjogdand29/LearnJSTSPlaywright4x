//Special Numeric Values
let positiveInfinity = Infinity; //Positive Infinity Literal
console.log(positiveInfinity); // Output: Infinity
console.log(typeof positiveInfinity); // Output: number

//Example of using Infinity in a mathematical operation
let result = 1 / 0; // Division by zero results in Infinity
console.log(result); // Output: Infinity
console.log(typeof result); // Output: number    

let negativeInfinity = -Infinity; //Negative Infinity Literal
console.log(negativeInfinity); // Output: -Infinity
console.log(typeof negativeInfinity); // Output: number

let notANumber = NaN; //NaN (Not-a-Number) Literal
console.log(notANumber); // Output: NaN
console.log(typeof notANumber); // Output: number 