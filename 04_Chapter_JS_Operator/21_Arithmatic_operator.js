// Arithmetic Operators in JavaScript
// Arithmetic operators are used to perform mathematical operations on numbers. They can be used with both numeric literals and variables that hold numeric values.

let a = 10; // Numeric Literal
let b = 5;  // Numeric Literal

// Addition (+)
let sum = a + b; // 10 + 5 = 15
console.log("Sum: " + sum); // Output: Sum: 15

// Subtraction (-)
let difference = a - b; // 10 - 5 = 5
console.log("Difference: " + difference); // Output: Difference: 5

// Multiplication (*)
let product = a * b; // 10 * 5 = 50
console.log("Product: " + product); // Output: Product: 50

// Division (/)
let quotient = a / b; // 10 / 5 = 2
console.log("Quotient: " + quotient); // Output: Quotient: 2

// Modulus (%)
let remainder = a % b; // 10 % 5 = 0
console.log("Remainder: " + remainder); // Output: Remainder: 0

// Exponentiation (**)
let power = a ** b; // 10 ** 5 = 100000
console.log("Power: " + power); // Output: Power: 100000  

