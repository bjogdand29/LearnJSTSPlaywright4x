//Comparison Operators in JavaScript
// Comparison operators are used to compare two values and return a boolean value (true or false) based on the comparison. They can be used with both numeric literals and variables that hold numeric values.

let a = 10; // Numeric Literal
let b = 5;  // Numeric Literal

// Equal to (==) 
console.log(a == b); // Output: false

// Not equal to (!=)
console.log(a != b); // Output: true

// Strict equal to (===) 
console.log(a === b); // Output: false

// Strict not equal to (!==)
console.log(a !== b); // Output: true

// Greater than (>)
console.log(a > b); // Output: true

// Less than (<)
console.log(a < b); // Output: false

// Greater than or equal to (>=)
console.log(a >= b); // Output: true

// Less than or equal to (<=)
console.log(a <= b); // Output: false 