// A for loop repeats a block of code while its condition is true.
//
// Syntax:
// for (initialization; condition; update) {
//     code to repeat
// }
//
// 1. Initialization runs once before the loop starts.
// 2. The condition is checked before each iteration. The loop continues
//    while the condition is true.
// 3. The loop body runs when the condition is true.
// 4. The update runs after the body, then the condition is checked again.
//
// This loop prints the numbers 1 through 10:
for (let number = 1; number < 10; number++) {
    console.log(number);
}

for (let i = 0; i < 10; i++) {
    console.log(i);
}